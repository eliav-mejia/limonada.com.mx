#!/usr/bin/env python3
"""Create / update pages/trajes/<slug>/index.html for every active suit in public/db/trajes.json.

    python3 tools/generar-paginas-traje.py

The page is rendered by renderSuit() in js/tienda.jsx, which reads the JSON at load time, so price, fabric or
option changes need no regeneration. Re-run only after adding a suit or changing slug, name, short or
base_price_mxn (copied into <head> and schema.org for search engines).
Paths are relative (../../../js/…) so the page works at the domain root and in any subfolder.
Suit folders whose slug is no longer in the database are listed, not deleted.
"""
import html
import json
from pathlib import Path

ROOT = Path(__file__).resolve().parent.parent
SITE = 'https://limonada.com.mx'
OUT = ROOT / 'pages' / 'trajes'
P = '../../../'
FONTS = ('https://fonts.googleapis.com/css2?family=Fraunces:ital,opsz,wght,SOFT,WONK@0,9..144,300..700,0..100,0..1;'
         '1,9..144,300..700,0..100,0..1&family=JetBrains+Mono:wght@400;500&family=Space+Grotesk:wght@400;500;600;700&display=swap')

TEMPLATE = """<!DOCTYPE html>
<html lang="es-MX">
<head>
    <meta charset="UTF-8">
    <meta name="viewport" content="width=device-width, initial-scale=1.0">
    <title>{title}</title>
    <meta name="description" content="{description}">
    <link rel="canonical" href="{url}">
    <meta property="og:title" content="{title}">
    <meta property="og:description" content="{description}">
    <meta property="og:url" content="{url}">
    <meta property="og:type" content="product">
    <link rel="icon" href="{P}img/favicon.svg" type="image/svg+xml">
    <meta name="theme-color" content="#171614">
    <script type="application/ld+json">{jsonld}</script>

    <!-- arranque.js first: sets LI_ROOT for every link and shows a message instead of a blank page if loading fails -->
    <script src="{P}js/arranque.js"></script>
    <script src="https://cdn.tailwindcss.com"></script>
    <script src="{P}js/tailwind.config.js"></script>
    <link rel="preconnect" href="https://fonts.googleapis.com">
    <link rel="preconnect" href="https://fonts.gstatic.com" crossorigin>
    <link href="{fonts}" rel="stylesheet">
    <link rel="stylesheet" href="{P}css/site.css">

    <script crossorigin src="https://cdnjs.cloudflare.com/ajax/libs/react/18.2.0/umd/react.production.min.js"></script>
    <script crossorigin src="https://cdnjs.cloudflare.com/ajax/libs/react-dom/18.2.0/umd/react-dom.production.min.js"></script>
    <script src="https://cdnjs.cloudflare.com/ajax/libs/babel-standalone/7.23.5/babel.min.js"></script>
</head>
<body>

    <div id="root"></div>
    <noscript><p style="padding:2rem;font-family:sans-serif">Limonada necesita JavaScript para mostrar la tienda. Escríbenos a hola@limonada.com.mx.</p></noscript>

    <script type="text/babel" src="{P}js/layout.jsx"></script>
    <script type="text/babel" src="{P}js/tienda.jsx"></script>
    <script type="text/babel">
        // Generated by tools/generar-paginas-traje.py. The suit is found from this page's URL.
        renderSuit();
    </script>
</body>
</html>
"""


def main():
    suits = json.loads((ROOT / 'public' / 'db' / 'trajes.json').read_text(encoding='utf-8'))['suits']
    active = [s for s in suits if s.get('active', True)]

    for s in active:
        url = f"{SITE}/pages/trajes/{s['slug']}/"
        title = f"{s['name']} · Traje a la medida · Limonada"
        jsonld = {
            '@context': 'https://schema.org', '@type': 'Product',
            'name': f"Traje a la medida {s['name']}", 'sku': s['sku'], 'description': s['description'],
            'brand': {'@type': 'Brand', 'name': 'Limonada'},
            'offers': {'@type': 'AggregateOffer', 'url': url, 'priceCurrency': 'MXN', 'lowPrice': s['base_price_mxn'],
                       'availability': 'https://schema.org/MadeToOrder'},
        }
        out = OUT / s['slug'] / 'index.html'
        out.parent.mkdir(parents=True, exist_ok=True)
        out.write_text(TEMPLATE.format(
            title=html.escape(title), description=html.escape(f"{s['short']} {s['description']}"), url=url, P=P, fonts=FONTS,
            jsonld=json.dumps(jsonld, ensure_ascii=False).replace('</', '<\\/'),
        ), encoding='utf-8', newline='\n')
        print(f"ok   pages/trajes/{s['slug']}/")

    slugs = {s['slug'] for s in active}
    for d in OUT.iterdir():
        if d.is_dir() and d.name not in slugs:
            print(f"OJO  pages/trajes/{d.name}/ ya no está en la base de datos: bórrala y añade la ruta a MOVED en 404.html")


if __name__ == '__main__':
    main()
